//! Regular temperament mappings (UMT-3.2 section 1.4).
//!
//! A mapping is an integer homomorphism `V: Lambda_B -> Gamma`. It need not be
//! surjective, and it is not a tuning: it sends lattice elements to integer
//! ambient coordinates, never to real interval sizes.

use alloc::sync::Arc;
use alloc::vec::Vec;

use crate::algebra::Z;
use crate::algebra::lattice::Sublattice;
use crate::algebra::matrix::IntMatrix;
use crate::algebra::normal_form::SmithNormalForm;
use crate::error::TemperamentError;
use crate::proportion::basis::Basis;
use crate::proportion::monzo::{Monzo, compatible};
use crate::temperament::image::{AmbientElem, AmbientLattice, ImageElem, ImageLattice};
use crate::temperament::kernel::KernelLattice;

/// The unvalidated form of a [`TemperamentMap`].
///
/// Holds exactly the declared data, with no derived structure and no shape
/// guarantee. Validation happens in [`TemperamentMap::new`] (prompt section
/// 12).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RawTemperamentMap {
    /// The domain basis `B`, spanning `Lambda_B`.
    pub domain: Arc<Basis>,
    /// The declared ambient lattice `Gamma`.
    pub ambient: Arc<AmbientLattice>,
    /// The mapping matrix, with one row per ambient coordinate and one column
    /// per basis generator.
    pub matrix: IntMatrix,
}

/// A validated regular temperament mapping `V: Lambda_B -> Gamma`.
///
/// UMT layer: L2 structural map, exact.
///
/// Construction computes the derived structure eagerly, so a validated mapping
/// always knows its rank, invariant factors, image, and kernel, and no
/// interior mutability or lazy cache is involved. Equality is presentation
/// equality over the domain, the ambient lattice, and the matrix; two matrices
/// that temper out the same commas are *not* equal, and
/// [`TemperamentMap::kernel`] comparison is the honest test for that.
///
/// # Examples
///
/// ```
/// use umt::temperament::{AmbientLattice, TemperamentMap};
/// use umt::{Basis, IntMatrix};
///
/// let basis = Basis::primes("umt:prime:2.3.5", &[2, 3, 5])?;
/// let steps = AmbientLattice::new("umt:edo:12", 1);
/// let map = TemperamentMap::from_rows(&basis, &steps, [[12i64, 19, 28]])?;
///
/// // Rank 1 mapping of a rank 3 lattice: the kernel has rank 2.
/// assert_eq!(map.rank(), 1);
/// assert_eq!(map.kernel().rank(), 2);
/// assert!(map.is_surjective());
///
/// // The syntonic comma is tempered out; the just fifth is not.
/// assert!(map.kills(&basis.monzo([-4, 4, -1])?)?);
/// assert!(!map.kills(&basis.monzo([-1, 1, 0])?)?);
///
/// // A map-derived kernel is saturated as a theorem, not as a check.
/// assert!(map.kernel().is_saturated());
/// # Ok::<(), Box<dyn core::error::Error>>(())
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TemperamentMap {
    domain: Arc<Basis>,
    ambient: Arc<AmbientLattice>,
    matrix: IntMatrix,
    invariant_factors: Vec<Z>,
    image: Arc<ImageLattice>,
    kernel: Arc<KernelLattice>,
}

impl TemperamentMap {
    /// Validates a raw mapping and computes its derived structure.
    ///
    /// # Errors
    ///
    /// Returns [`TemperamentError::ShapeMismatch`] if the matrix shape does
    /// not match the domain and ambient ranks.
    pub fn new(raw: RawTemperamentMap) -> Result<Self, TemperamentError> {
        let RawTemperamentMap {
            domain,
            ambient,
            matrix,
        } = raw;

        if matrix.rows() != ambient.rank() || matrix.cols() != domain.rank() {
            return Err(TemperamentError::ShapeMismatch {
                expected_rows: ambient.rank(),
                expected_cols: domain.rank(),
                found_rows: matrix.rows(),
                found_cols: matrix.cols(),
            });
        }

        // The image is generated by the columns of the matrix.
        let image = ImageLattice::new(
            &ambient,
            Sublattice::from_generators(ambient.rank(), &matrix)?,
        )?;

        // The kernel comes from the Smith normal form. It is saturated
        // automatically because the ambient group is torsion-free (UMT-3.2
        // section 1.4.1), so it is built through the map-kernel constructor,
        // which performs no redundant saturation check.
        let smith = SmithNormalForm::of(&matrix);
        let kernel = KernelLattice::of_map(&domain, &smith.kernel_basis())?;

        Ok(Self {
            domain,
            ambient,
            matrix,
            invariant_factors: smith.invariant_factors().to_vec(),
            image,
            kernel,
        })
    }

    /// Builds a mapping from rows of integers.
    ///
    /// # Errors
    ///
    /// Returns [`TemperamentError::Matrix`] if the rows are ragged, and
    /// [`TemperamentError::ShapeMismatch`] if the resulting shape does not
    /// match the declared ranks.
    pub fn from_rows<R, C, T>(
        domain: &Arc<Basis>,
        ambient: &Arc<AmbientLattice>,
        rows: R,
    ) -> Result<Self, TemperamentError>
    where
        R: IntoIterator<Item = C>,
        C: IntoIterator<Item = T>,
        T: Into<Z>,
    {
        Self::new(RawTemperamentMap {
            domain: Arc::clone(domain),
            ambient: Arc::clone(ambient),
            matrix: IntMatrix::from_rows(rows)?,
        })
    }

    /// The domain basis.
    #[must_use]
    pub fn domain(&self) -> &Arc<Basis> {
        &self.domain
    }

    /// The declared ambient lattice `Gamma`.
    #[must_use]
    pub fn ambient(&self) -> &Arc<AmbientLattice> {
        &self.ambient
    }

    /// The exact mapping matrix.
    #[must_use]
    pub fn matrix(&self) -> &IntMatrix {
        &self.matrix
    }

    /// The rank of the mapping, equal to the rank of its image.
    #[must_use]
    pub fn rank(&self) -> usize {
        self.invariant_factors.len()
    }

    /// The invariant factors of the mapping matrix.
    ///
    /// These describe image primitivity: for a full-row-rank mapping their
    /// product is the gcd of the maximal minors, so the mapping is surjective
    /// exactly when they are all 1 and the rank equals the ambient rank
    /// (UMT-3.2 section 1.4.2). They say nothing about kernel saturation,
    /// which is automatic.
    #[must_use]
    pub fn invariant_factors(&self) -> &[Z] {
        &self.invariant_factors
    }

    /// The reachable image `H = im(V)`.
    #[must_use]
    pub fn image(&self) -> &Arc<ImageLattice> {
        &self.image
    }

    /// The kernel `K = ker(V)`, the group of tempered-out commas.
    #[must_use]
    pub fn kernel(&self) -> &Arc<KernelLattice> {
        &self.kernel
    }

    /// Whether the mapping reaches all of the ambient lattice.
    #[must_use]
    pub fn is_surjective(&self) -> bool {
        self.image.is_full()
    }

    /// Applies the mapping, giving an ambient coordinate.
    ///
    /// # Errors
    ///
    /// Returns [`TemperamentError::BasisMismatch`] if the monzo is over an
    /// unrelated basis.
    pub fn apply(&self, monzo: &Monzo) -> Result<AmbientElem, TemperamentError> {
        if !compatible(monzo.basis(), &self.domain) {
            return Err(TemperamentError::BasisMismatch {
                expected: self.domain.id().clone(),
                found: monzo.basis().id().clone(),
            });
        }
        let coordinates = self.matrix.apply(monzo.exponents())?;
        self.ambient.element(coordinates)
    }

    /// Applies the mapping, giving intrinsic image coordinates.
    ///
    /// Every mapped element is in the image by construction, so this fails
    /// only on a basis mismatch.
    ///
    /// # Errors
    ///
    /// Returns [`TemperamentError::BasisMismatch`] if the monzo is over an
    /// unrelated basis.
    pub fn apply_to_image(&self, monzo: &Monzo) -> Result<ImageElem, TemperamentError> {
        let ambient = self.apply(monzo)?;
        self.image.from_ambient(&ambient)
    }

    /// Whether a monzo is tempered out, that is, lies in the kernel.
    ///
    /// # Errors
    ///
    /// Returns [`TemperamentError::BasisMismatch`] if the monzo is over an
    /// unrelated basis.
    pub fn kills(&self, monzo: &Monzo) -> Result<bool, TemperamentError> {
        Ok(self.apply(monzo)?.is_zero())
    }
}

#[cfg(test)]
mod tests {
    use super::TemperamentMap;
    use crate::algebra::Z;
    use crate::error::TemperamentError;
    use crate::proportion::Basis;
    use crate::temperament::image::AmbientLattice;
    use alloc::sync::Arc;

    fn five_limit() -> Arc<Basis> {
        Basis::primes("umt:prime:2.3.5", &[2, 3, 5]).unwrap()
    }

    #[test]
    fn shape_is_validated() {
        let basis = five_limit();
        let steps = AmbientLattice::new("umt:edo:12", 1);
        assert_eq!(
            TemperamentMap::from_rows(&basis, &steps, [[12i64, 19]]).unwrap_err(),
            TemperamentError::ShapeMismatch {
                expected_rows: 1,
                expected_cols: 3,
                found_rows: 1,
                found_cols: 2,
            }
        );
    }

    #[test]
    fn kernel_membership_matches_mapping_to_zero() {
        let basis = five_limit();
        let steps = AmbientLattice::new("umt:edo:12", 1);
        let map = TemperamentMap::from_rows(&basis, &steps, [[12i64, 19, 28]]).unwrap();

        for exponents in [[-4i64, 4, -1], [-19, 12, 0], [0, 0, 0], [7, -3, -1]] {
            let monzo = basis.monzo(exponents).unwrap();
            assert_eq!(
                map.kills(&monzo).unwrap(),
                map.kernel().contains(&monzo).unwrap(),
                "kernel membership must agree with mapping to zero for {exponents:?}"
            );
        }
    }

    #[test]
    fn a_rank_two_mapping_keeps_its_image_and_kernel_apart() {
        // Meantone as a rank-2 mapping: octaves and fifths.
        let basis = five_limit();
        let ambient = AmbientLattice::new("umt:meantone-coords", 2);
        let map = TemperamentMap::from_rows(&basis, &ambient, [[1i64, 0, -4], [0, 1, 4]]).unwrap();

        assert_eq!(map.rank(), 2);
        assert!(map.is_surjective());
        assert_eq!(map.kernel().rank(), 1);
        // The kernel is exactly the syntonic comma.
        assert_eq!(
            map.kernel().basis_monzos(),
            alloc::vec![basis.monzo([4, -4, 1]).unwrap()]
        );
        assert!(map.kills(&basis.monzo([-4, 4, -1]).unwrap()).unwrap());
    }

    #[test]
    fn the_zero_mapping_has_everything_in_its_kernel() {
        let basis = five_limit();
        let ambient = AmbientLattice::new("umt:zero", 1);
        let map = TemperamentMap::from_rows(&basis, &ambient, [[0i64, 0, 0]]).unwrap();

        assert_eq!(map.rank(), 0);
        assert!(!map.is_surjective());
        assert_eq!(map.image().rank(), 0);
        assert_eq!(map.kernel().rank(), 3);
        assert!(map.kills(&basis.monzo([1, 0, 0]).unwrap()).unwrap());
    }

    #[test]
    fn foreign_monzos_are_rejected() {
        let basis = five_limit();
        let other = Basis::primes("umt:prime:2.3.7", &[2, 3, 7]).unwrap();
        let steps = AmbientLattice::new("umt:edo:12", 1);
        let map = TemperamentMap::from_rows(&basis, &steps, [[12i64, 19, 28]]).unwrap();
        assert!(matches!(
            map.apply(&other.monzo([1, 0, 0]).unwrap()),
            Err(TemperamentError::BasisMismatch { .. })
        ));
    }

    #[test]
    fn image_coordinates_differ_from_ambient_coordinates() {
        let basis = five_limit();
        let steps = AmbientLattice::new("umt:edo:6", 1);
        let map = TemperamentMap::from_rows(&basis, &steps, [[6i64, 10, 14]]).unwrap();

        let octave = basis.monzo([1, 0, 0]).unwrap();
        assert_eq!(map.apply(&octave).unwrap().coordinates(), &[Z::from(6)]);
        assert_eq!(
            map.apply_to_image(&octave).unwrap().coordinates(),
            &[Z::from(3)],
            "the octave is 6 ambient steps but 3 image units"
        );
    }
}
